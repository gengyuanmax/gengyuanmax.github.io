"""Shared output for mark sources: two ink-density plates -> review PNGs + data-URI module."""
import base64, pathlib
import numpy as np
from PIL import Image

here = pathlib.Path(__file__).parent

def write(name, plates, note, screens=None):
    """plates: {'a': density array (H, W) 0..1, 'b': ..., optional 'c' yellow, 'd' dark}.
    Extra sub-plates of an ink are keyed 'b2', 'b3' ...; screens optionally gives a sub-plate
    its own dot shape/angle, e.g. {'b2': {'shape': 'diamond', 'angle': 45}}."""
    out = here / 'out'; out.mkdir(exist_ok=True)
    lines = []
    for plate, dens in plates.items():
        img = np.zeros(dens.shape + (4,), np.uint8); img[..., 3] = np.round(np.clip(dens, 0, 1) * 255)
        path = out / f'{name}-{plate}.png'; Image.fromarray(img).save(path, optimize=True)
        lines.append(f"export const plate{plate.upper()}='data:image/png;base64,{base64.b64encode(path.read_bytes()).decode()}';")
    ts = here.parent.parent / 'src' / 'design' / 'assets' / f'mark-{name}.ts'
    if screens:
        import json
        lines.append(f"export const screens={json.dumps(screens, sort_keys=True)};")
    ts.write_text(f"// Generated by {note}. Do not edit.\n" + "\n".join(lines) + "\n")
    print('wrote', ts, sorted(plates))
