"""Shared output for mark sources: two ink-density plates -> review PNGs + data-URI module."""
import base64, pathlib
import numpy as np
from PIL import Image

here = pathlib.Path(__file__).parent

def write(name, a, b, note):
    """a, b: float arrays (H, W) of ink density 0..1 for vermilion (A) and blue (B)."""
    out = here / 'out'; out.mkdir(exist_ok=True)
    uris = {}
    for plate, dens in (('a', a), ('b', b)):
        img = np.zeros(dens.shape + (4,), np.uint8); img[..., 3] = np.round(np.clip(dens, 0, 1) * 255)
        path = out / f'{name}-{plate}.png'; Image.fromarray(img).save(path, optimize=True)
        uris[plate] = 'data:image/png;base64,' + base64.b64encode(path.read_bytes()).decode()
    ts = here.parent.parent / 'src' / 'design' / 'assets' / f'mark-{name}.ts'
    ts.write_text(f"// Generated by {note}. Do not edit.\nexport const plateA='{uris['a']}';\nexport const plateB='{uris['b']}';\n")
    print('wrote', ts)
