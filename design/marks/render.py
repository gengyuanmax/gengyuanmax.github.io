"""Render a mark scene with Blender (bpy) into two ink-density plates.

python3 design/marks/render.py icq  ->  src/design/assets/mark-icq.ts
(plates also in design/marks/out/ for review; 360x220 source at 2x)

Blender handles projection, occlusion and anti-aliasing. Plates are plain
alpha masks (black, alpha = ink density); the print pipeline does the rest.
"""
import sys, importlib.util, pathlib, math
import bpy, numpy as np
from PIL import Image

name = sys.argv[1]
here = pathlib.Path(__file__).parent
spec = importlib.util.spec_from_file_location(name, here / f'{name}.py'); scene_mod = importlib.util.module_from_spec(spec); spec.loader.exec_module(scene_mod)

bpy.ops.wm.read_factory_settings(use_empty=True)
sc = bpy.context.scene
W, H = 720, 440

def ink(label, top, x, y):
    """Emission material: colour = (densityA, densityB, 0) chosen by world normal."""
    m = bpy.data.materials.new(label); m.use_nodes = True
    nt = m.node_tree; nt.nodes.clear()
    out = nt.nodes.new('ShaderNodeOutputMaterial'); em = nt.nodes.new('ShaderNodeEmission')
    geo = nt.nodes.new('ShaderNodeNewGeometry'); sep = nt.nodes.new('ShaderNodeSeparateXYZ')
    nt.links.new(geo.outputs['Normal'], sep.inputs[0])
    def weighted(axis_out, val):
        mx = nt.nodes.new('ShaderNodeMath'); mx.operation = 'MAXIMUM'; mx.inputs[1].default_value = 0
        nt.links.new(axis_out, mx.inputs[0])
        mul = nt.nodes.new('ShaderNodeVectorMath'); mul.operation = 'SCALE'
        mul.inputs[0].default_value = (val[0], val[1], 0); nt.links.new(mx.outputs[0], mul.inputs['Scale'])
        return mul
    parts = [weighted(sep.outputs['Z'], top), weighted(sep.outputs['X'], x), weighted(sep.outputs['Y'], y)]
    a1 = nt.nodes.new('ShaderNodeVectorMath'); a1.operation = 'ADD'
    nt.links.new(parts[0].outputs[0], a1.inputs[0]); nt.links.new(parts[1].outputs[0], a1.inputs[1])
    a2 = nt.nodes.new('ShaderNodeVectorMath'); a2.operation = 'ADD'
    nt.links.new(a1.outputs[0], a2.inputs[0]); nt.links.new(parts[2].outputs[0], a2.inputs[1])
    nt.links.new(a2.outputs[0], em.inputs['Color']); nt.links.new(em.outputs[0], out.inputs[0])
    return m

target = scene_mod.build(ink)

# Isometric orthographic camera, auto-framed to the scene with a fixed margin.
cam = bpy.data.objects.new('cam', bpy.data.cameras.new('cam')); sc.collection.objects.link(cam); sc.camera = cam
cam.data.type = 'ORTHO'
cam.rotation_euler = (math.radians(54.7356), 0, math.radians(135))
d = 30
cam.location = (target[0] + d*.57735, target[1] + d*.57735, target[2] + d*.57735)
sc.render.resolution_x, sc.render.resolution_y = W, H
bpy.context.view_layer.update()
from mathutils import Vector
inv = cam.matrix_world.inverted()
pts = [inv @ (o.matrix_world @ Vector(c)) for o in sc.objects if o.type == 'MESH' for c in o.bound_box]
xs, ys = [p.x for p in pts], [p.y for p in pts]
margin = 1.1
w, h = (max(xs)-min(xs))*margin, (max(ys)-min(ys))*margin
cam.data.ortho_scale = max(w, h*W/H)
cam.data.shift_x = (max(xs)+min(xs))/2/cam.data.ortho_scale
cam.data.shift_y = (max(ys)+min(ys))/2/cam.data.ortho_scale

sc.render.engine = 'CYCLES'; sc.cycles.device = 'CPU'; sc.cycles.samples = 64
sc.view_settings.view_transform = 'Standard'; sc.render.film_transparent = True
sc.world = bpy.data.worlds.new('w')
out = here / 'out' / f'{name}-render.png'; out.parent.mkdir(exist_ok=True); sc.render.filepath = str(out); sc.render.image_settings.color_mode = 'RGBA'
bpy.ops.render.render(write_still=True)

rgba = np.asarray(Image.open(out).convert('RGBA')).astype(np.float32) / 255
alpha = rgba[..., 3]
dest = here / 'out'; dest.mkdir(parents=True, exist_ok=True)
for ch, plate in ((0, 'a'), (1, 'b')):
    density = np.clip(rgba[..., ch] * alpha, 0, 1)   # premultiplied colour = density × coverage
    img = np.zeros((H, W, 4), np.uint8); img[..., 3] = np.round(density * 255)
    Image.fromarray(img).save(dest / f'{name}-{plate}.png', optimize=True)
# The print pipeline reads plates as data URIs in both Node and the browser.
import base64
ts = here.parent.parent / 'src' / 'design' / 'assets' / f'mark-{name}.ts'
uris = {p: 'data:image/png;base64,' + base64.b64encode((dest / f'{name}-{p}.png').read_bytes()).decode() for p in 'ab'}
ts.write_text(f"// Generated by design/marks/render.py {name}. Do not edit; edit design/marks/{name}.py.\nexport const plateA='{uris['a']}';\nexport const plateB='{uris['b']}';\n")
print('wrote', dest / f'{name}-a.png', dest / f'{name}-b.png')
